//! Token definitions.

use crate::error::Span;

#[derive(Debug, Clone, PartialEq)]
pub enum StrPart {
    Lit(String),
    /// Interpolated code `#{ ... }` with the location of its first character.
    Code(String, Span),
}

#[derive(Debug, Clone, PartialEq)]
pub enum Tok {
    Number(f64),
    Str(Vec<StrPart>),
    Symbol(String),
    Ident(String),
    Const(String),
    IVar(String),
    GVar(String),
    // keywords
    Function,
    Class,
    Module,
    Import,
    If,
    Elsif,
    Else,
    While,
    For,
    In,
    Repeat,
    Times,
    Return,
    Break,
    Next,
    End,
    True,
    False,
    Nil,
    SelfKw,
    Super,
    And,
    Or,
    Not,
    // punctuation / operators
    LParen,
    RParen,
    LBracket,
    RBracket,
    LBrace,
    RBrace,
    Comma,
    Dot,
    Colon,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    StarStar,
    Eq,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    EqEq,
    BangEq,
    Lt,
    Gt,
    LtEq,
    GtEq,
    AmpAmp,
    PipePipe,
    Bang,
    Newline,
    Eof,
}

impl Tok {
    pub fn describe(&self) -> String {
        match self {
            Tok::Number(n) => format!("number {}", n),
            Tok::Str(_) => "string".into(),
            Tok::Symbol(s) => format!("symbol :{}", s),
            Tok::Ident(s) | Tok::Const(s) => format!("'{}'", s),
            Tok::IVar(s) => format!("'@{}'", s),
            Tok::GVar(s) => format!("'${}'", s),
            Tok::Newline => "end of line".into(),
            Tok::Eof => "end of file".into(),
            other => format!("'{}'", other.text()),
        }
    }

    pub fn text(&self) -> &'static str {
        match self {
            Tok::Function => "function",
            Tok::Class => "class",
            Tok::Module => "module",
            Tok::Import => "import",
            Tok::If => "if",
            Tok::Elsif => "elsif",
            Tok::Else => "else",
            Tok::While => "while",
            Tok::For => "for",
            Tok::In => "in",
            Tok::Repeat => "repeat",
            Tok::Times => "times",
            Tok::Return => "return",
            Tok::Break => "break",
            Tok::Next => "next",
            Tok::End => "end",
            Tok::True => "true",
            Tok::False => "false",
            Tok::Nil => "nil",
            Tok::SelfKw => "self",
            Tok::Super => "super",
            Tok::And => "and",
            Tok::Or => "or",
            Tok::Not => "not",
            Tok::LParen => "(",
            Tok::RParen => ")",
            Tok::LBracket => "[",
            Tok::RBracket => "]",
            Tok::LBrace => "{",
            Tok::RBrace => "}",
            Tok::Comma => ",",
            Tok::Dot => ".",
            Tok::Colon => ":",
            Tok::Plus => "+",
            Tok::Minus => "-",
            Tok::Star => "*",
            Tok::Slash => "/",
            Tok::Percent => "%",
            Tok::StarStar => "**",
            Tok::Eq => "=",
            Tok::PlusEq => "+=",
            Tok::MinusEq => "-=",
            Tok::StarEq => "*=",
            Tok::SlashEq => "/=",
            Tok::EqEq => "==",
            Tok::BangEq => "!=",
            Tok::Lt => "<",
            Tok::Gt => ">",
            Tok::LtEq => "<=",
            Tok::GtEq => ">=",
            Tok::AmpAmp => "&&",
            Tok::PipePipe => "||",
            Tok::Bang => "!",
            _ => "?",
        }
    }
}

pub fn keyword(s: &str) -> Option<Tok> {
    Some(match s {
        "function" => Tok::Function,
        "class" => Tok::Class,
        "module" => Tok::Module,
        "import" => Tok::Import,
        "if" => Tok::If,
        "elsif" => Tok::Elsif,
        "else" => Tok::Else,
        "while" => Tok::While,
        "for" => Tok::For,
        "in" => Tok::In,
        "repeat" => Tok::Repeat,
        "times" => Tok::Times,
        "return" => Tok::Return,
        "break" => Tok::Break,
        "next" => Tok::Next,
        "end" => Tok::End,
        "true" => Tok::True,
        "false" => Tok::False,
        "nil" => Tok::Nil,
        "self" => Tok::SelfKw,
        "super" => Tok::Super,
        "and" => Tok::And,
        "or" => Tok::Or,
        "not" => Tok::Not,
        _ => return None,
    })
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub tok: Tok,
    pub span: Span,
}
